package Conditionals;

public class VolumeofPrism {
    public static void main(String[] args){
        double height=10.0;
        double length=5.0;
        double width=4.0;
        double baseArea=length*width; 
        double volume=baseArea*height;
        System.out.println("Volume of Prism is:"+volume);
    }
    
}
